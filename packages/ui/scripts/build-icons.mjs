// Generates src/icons/icons.gen.tsx and src/icons/icon-names.gen.ts from src/icons/svg/*.svg.
// The folder is the manifest: drop `name.svg` in it, run `pnpm build`, commit the output.
// Every SVG is a 16×16 outline; fills and strokes may only be currentColor or none, so icons
// inherit the text colour and theme with it. Unknown attributes fail the build.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const svgDir = join(here, '..', 'src', 'icons', 'svg');
const outDir = join(here, '..', 'src', 'icons');

const NAME = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;
const ELEMENTS = new Set(['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);
const ATTRS = {
  d: 'd',
  cx: 'cx',
  cy: 'cy',
  r: 'r',
  rx: 'rx',
  ry: 'ry',
  x: 'x',
  y: 'y',
  x1: 'x1',
  y1: 'y1',
  x2: 'x2',
  y2: 'y2',
  width: 'width',
  height: 'height',
  points: 'points',
  fill: 'fill',
  stroke: 'stroke',
  'stroke-width': 'strokeWidth',
  'stroke-linecap': 'strokeLinecap',
  'stroke-linejoin': 'strokeLinejoin',
  'fill-rule': 'fillRule',
  'clip-rule': 'clipRule',
  transform: 'transform',
};
const COLOR = /^(currentColor|none)$/;

// Sort the names, not the file names: `eye-off.svg` sorts before `eye.svg`, `eye` before `eye-off`.
const names = readdirSync(svgDir)
  .filter((f) => f.endsWith('.svg'))
  .map((f) => f.slice(0, -4))
  .sort();
const seen = new Set();
const errors = [];
for (const name of names) {
  if (!NAME.test(name)) errors.push(`${name}.svg: name must be kebab-case`);
  if (seen.has(name)) errors.push(`${name}.svg: duplicate`);
  seen.add(name);
}

function toJsx(name, svg) {
  const root = svg.match(/^\s*<svg\s+([^>]*)>([\s\S]*)<\/svg>\s*$/);
  if (!root) throw new Error(`${name}.svg: expected a single <svg> root`);
  const [, rootAttrs, inner] = root;
  if (!/viewBox="0 0 16 16"/.test(rootAttrs)) throw new Error(`${name}.svg: viewBox must be "0 0 16 16"`);
  const out = [];
  const tag = /<([a-z]+)\s*([^>]*?)\s*\/>/g;
  let rest = inner;
  let m;
  while ((m = tag.exec(inner))) {
    const [, el, attrs] = m;
    if (!ELEMENTS.has(el)) throw new Error(`${name}.svg: <${el}> is not allowed`);
    const props = [];
    const attr = /([a-z0-9-]+)="([^"]*)"/g;
    let a;
    while ((a = attr.exec(attrs))) {
      const [, key, value] = a;
      const jsxKey = ATTRS[key];
      if (!jsxKey) throw new Error(`${name}.svg: attribute ${key} on <${el}> is not allowed`);
      if ((key === 'fill' || key === 'stroke') && !COLOR.test(value)) {
        throw new Error(`${name}.svg: ${key}="${value}" must be currentColor or none`);
      }
      props.push(`${jsxKey}="${value}"`);
    }
    out.push(`<${el} ${props.join(' ')} />`);
    rest = rest.replace(m[0], '');
  }
  if (rest.trim() !== '') throw new Error(`${name}.svg: unexpected content: ${rest.trim().slice(0, 40)}`);
  return out;
}

const components = [];
for (const name of names) {
  try {
    const jsx = toJsx(name, readFileSync(join(svgDir, `${name}.svg`), 'utf8'));
    const pascal = name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
    components.push(
      `/** \`${name}\` */\nexport function ${pascal}Icon(props: IconGlyphProps) {\n  return (\n    <Icon {...props}>\n${jsx.map((l) => `      ${l}`).join('\n')}\n    </Icon>\n  );\n}`,
    );
  } catch (e) {
    errors.push(e.message);
  }
}
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const header = `// Generated by scripts/build-icons.mjs from src/icons/svg/*.svg. Do not edit; add an SVG and run \`pnpm build\`.\n`;
writeFileSync(
  join(outDir, 'icons.gen.tsx'),
  `${header}import { Icon, type IconGlyphProps } from '../components/Icon/Icon';\n\n${components.join('\n\n')}\n`,
);
writeFileSync(
  join(outDir, 'icon-names.gen.ts'),
  `${header}/** Every icon shipped by this package, as \`<Name>Icon\` components. */\nexport const iconNames = [\n${names.map((n) => `  '${n}',`).join('\n')}\n] as const;\nexport type IconName = (typeof iconNames)[number];\n`,
);
console.log(`icons: ${names.length} components`);
