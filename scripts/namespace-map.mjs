// Writes scripts/namespace-map.json: every rename the Protokit migration makes (ADR 0009, docs/protokit-rename-plan.md).
// Run once, before the rename, from the repo root after `pnpm build`:
//
//   node scripts/namespace-map.mjs
//
// It reads the component stylesheets (packages/ui/src/styles/*.css) for class blocks and keyframes, and the built
// token JSON (packages/tokens/dist/json/tokens.json) for token categories. The committed map is the record the codemod
// (scripts/codemod-namespace.mjs) applies here and in consumers; after the rename there is nothing left to read, so it
// is not regenerated.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FROM = 'sc';
const TO = 'proto';

// ITCSS namespace per block (ADR 0009, decisions 2 and 3). Every block not listed is a component (`c-`).
const NAMESPACES = {
  o: ['stack', 'inline'],
  u: ['visually-hidden', 'focus-ring'],
  t: ['on-accent'],
};

const stylesDir = join(root, 'packages/ui/src/styles');
const css = readdirSync(stylesDir)
  .filter((f) => f.endsWith('.css'))
  .sort()
  .map((f) => readFileSync(join(stylesDir, f), 'utf8'))
  .join('\n')
  // Comments mention class names in prose; only selectors count.
  .replace(/\/\*[\s\S]*?\*\//g, '');

const classNames = [
  ...new Set([...css.matchAll(new RegExp(`\\.${FROM}-([a-z0-9][a-z0-9_-]*[a-z0-9])`, 'g'))].map((m) => m[1])),
].sort();
const keyframes = [
  ...new Set([...css.matchAll(new RegExp(`@keyframes\\s+${FROM}-([a-z0-9-]+)`, 'g'))].map((m) => m[1])),
].sort();

const namespaceOf = (block) =>
  Object.entries(NAMESPACES).find(([, list]) => list.includes(block))?.[0] ?? 'c';
const blocks = Object.fromEntries(
  [...new Set(classNames.map((c) => c.split('__')[0]))].sort().map((b) => [b, namespaceOf(b)]),
);
for (const list of Object.values(NAMESPACES))
  for (const b of list)
    if (!blocks[b]) throw new Error(`namespace table names "${b}", which no stylesheet uses`);

let tokens;
try {
  tokens = JSON.parse(readFileSync(join(root, 'packages/tokens/dist/json/tokens.json'), 'utf8'));
} catch {
  throw new Error('packages/tokens/dist/json/tokens.json is missing: run `pnpm build` first');
}
if (tokens.prefix !== FROM) throw new Error(`tokens.json prefix is "${tokens.prefix}", expected "${FROM}"`);
const tokenCategories = [...new Set(Object.keys(tokens.light).map((k) => k.split('-')[1]))].sort();
for (const c of tokenCategories)
  if (Object.keys(blocks).some((b) => b === c || b.startsWith(`${c}-`)))
    throw new Error(`token category "${c}" is also a class block; the codemod could not tell them apart`);

const rename = (name) => {
  const [block, ...element] = name.split('__');
  return `${blocks[block]}-${TO}-${block}${element.length ? `__${element.join('__')}` : ''}`;
};

const map = {
  $comment:
    'Generated by scripts/namespace-map.mjs before the Protokit rename. Applied by scripts/codemod-namespace.mjs. ' +
    '"classes" lists every class the stylesheets declared, for reference; the codemod renames any class whose block is in "blocks".',
  from: FROM,
  to: TO,
  packages: { '@salemcobalt/tokens': '@protokit/tokens', '@salemcobalt/ui': '@protokit/ui' },
  namespaces: NAMESPACES,
  blocks,
  keyframes: Object.fromEntries(keyframes.map((k) => [`${FROM}-${k}`, `${TO}-${k}`])),
  tokenCategories,
  classes: Object.fromEntries(classNames.map((c) => [`${FROM}-${c}`, rename(c)])),
};

writeFileSync(join(root, 'scripts/namespace-map.json'), `${JSON.stringify(map, null, 2)}\n`);
console.log(
  `namespace-map.json: ${Object.keys(blocks).length} blocks, ${classNames.length} classes, ${keyframes.length} keyframes, ${tokenCategories.length} token categories`,
);
